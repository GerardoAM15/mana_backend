-- En DBeaver: abrir el archivo y ejecutar con Alt + X (sin seleccionar nada).
--
-- Solo AGREGA tablas: no modifica ninguna tabla existente, así que el
-- backend actual sigue funcionando igual hasta que se agreguen las entidades.
--
--   series_comprobante    series SUNAT por local (B001, F001, BC01, FC01) y su correlativo
--   comprobantes          boleta, factura o nota de crédito emitida (cabecera + respuesta SUNAT)
--   comprobante_detalles  líneas tal como se enviaron a SUNAT (copia congelada)
--
-- Reglas que soporta:
--   * Un comprobante se origina en una venta, en un contrato, o (nota de
--     crédito) en otro comprobante. Exactamente uno de los tres.
--   * Una venta o un contrato tiene como máximo UNA boleta/factura vigente
--     (las anuladas no cuentan).
--   * Factura: el receptor debe tener RUC (tipo de documento SUNAT '6').
--   * Los datos del receptor y los montos se copian al emitir (no cambian
--     si después se edita el cliente o la tarifa).
--   * total = operaciones gravadas + IGV. El porcentaje de IGV se guarda
--     en cada comprobante (lo fija la configuración del backend).
--   * Serie y número son únicos: B001-00000001.
-- Catálogo SUNAT 06 (tipo de documento del receptor):
--   '1' DNI · '6' RUC · '0' sin documento (boletas de montos menores)
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. Series y correlativos de comprobantes
-- ---------------------------------------------------------------------
create table series_comprobante (
    id              number(19,0) generated by default as identity,
    local_id        number(19,0)       not null,
    tipo            varchar2(24 char)  not null,
    serie           varchar2(4 char)   not null,
    ultimo_numero   number(8,0)        default 0 not null,
    activo          number(1,0)        default 1 not null,
    version         number(19,0)       default 0 not null,
    creado_en       timestamp(9) with time zone not null,
    actualizado_en  timestamp(9) with time zone not null,
    creado_por      varchar2(160 char) not null,
    actualizado_por varchar2(160 char) not null,
    constraint pk_series_comprobante primary key (id),
    constraint uq_series_comprobante unique (serie),
    constraint fk_series_local foreign key (local_id) references locales (id),
    constraint ck_series_tipo check (tipo in ('BOLETA', 'FACTURA', 'NOTA_CREDITO_BOLETA', 'NOTA_CREDITO_FACTURA')),
    constraint ck_series_formato check (
        (tipo = 'BOLETA'               and regexp_like(serie, '^B[0-9]{3}$')) or
        (tipo = 'FACTURA'              and regexp_like(serie, '^F[0-9]{3}$')) or
        (tipo = 'NOTA_CREDITO_BOLETA'  and regexp_like(serie, '^B[A-Z0-9]{3}$')) or
        (tipo = 'NOTA_CREDITO_FACTURA' and regexp_like(serie, '^F[A-Z0-9]{3}$'))),
    constraint ck_series_numero check (ultimo_numero between 0 and 99999999),
    constraint ck_series_activo check (activo in (0,1))
);

-- ---------------------------------------------------------------------
-- 2. Comprobantes (cabecera, receptor, montos y respuesta de SUNAT)
-- ---------------------------------------------------------------------
create table comprobantes (
    id                  number(19,0) generated by default as identity,
    local_id            number(19,0)       not null,
    serie_id            number(19,0)       not null,
    tipo                varchar2(16 char)  not null,
    serie               varchar2(4 char)   not null,
    numero              number(8,0)        not null,
    venta_id            number(19,0),
    contrato_id         number(19,0),
    referencia_id       number(19,0),
    motivo_codigo       varchar2(2 char),
    motivo_descripcion  varchar2(250 char),
    fecha_emision       timestamp(9)       not null,
    moneda              varchar2(3 char)   default 'PEN' not null,
    receptor_tipo_doc   varchar2(1 char)   not null,
    receptor_num_doc    varchar2(15 char),
    receptor_nombre     varchar2(160 char) not null,
    receptor_direccion  varchar2(250 char),
    porcentaje_igv      number(5,2)        not null,
    op_gravadas         number(14,2)       not null,
    igv                 number(14,2)       not null,
    total               number(14,2)       not null,
    estado              varchar2(16 char)  not null,
    ambiente            varchar2(12 char)  not null,
    sunat_codigo        varchar2(10 char),
    sunat_mensaje       varchar2(500 char),
    hash                varchar2(100 char),
    xml                 clob,
    cdr                 clob,
    intentos            number(5,0)        default 0 not null,
    ultimo_intento_en   timestamp(9),
    version             number(19,0)       default 0 not null,
    creado_en           timestamp(9) with time zone not null,
    actualizado_en      timestamp(9) with time zone not null,
    creado_por          varchar2(160 char) not null,
    actualizado_por     varchar2(160 char) not null,
    constraint pk_comprobantes primary key (id),
    constraint uq_comprobantes_serie_numero unique (serie, numero),
    constraint fk_comprobantes_local foreign key (local_id) references locales (id),
    constraint fk_comprobantes_serie foreign key (serie_id) references series_comprobante (id),
    constraint fk_comprobantes_venta foreign key (venta_id) references ventas (id),
    constraint fk_comprobantes_contrato foreign key (contrato_id) references contratos (id),
    constraint fk_comprobantes_referencia foreign key (referencia_id) references comprobantes (id),
    constraint ck_comprobantes_tipo check (tipo in ('BOLETA', 'FACTURA', 'NOTA_CREDITO')),
    constraint ck_comprobantes_estado check (estado in ('PENDIENTE', 'ACEPTADO', 'OBSERVADO', 'RECHAZADO', 'ERROR', 'ANULADO')),
    constraint ck_comprobantes_ambiente check (ambiente in ('BETA', 'PRODUCCION')),
    constraint ck_comprobantes_moneda check (moneda = 'PEN'),
    constraint ck_comprobantes_numero check (numero between 1 and 99999999),
    -- Origen: venta, contrato o (nota de crédito) otro comprobante; exactamente uno.
    constraint ck_comprobantes_origen check (
        (tipo in ('BOLETA', 'FACTURA') and referencia_id is null
            and ((venta_id is not null and contrato_id is null) or (venta_id is null and contrato_id is not null))) or
        (tipo = 'NOTA_CREDITO' and referencia_id is not null and venta_id is null and contrato_id is null
            and motivo_codigo is not null and motivo_descripcion is not null)),
    constraint ck_comprobantes_receptor check (
        receptor_tipo_doc in ('0', '1', '6') and
        (receptor_tipo_doc = '0' or receptor_num_doc is not null) and
        (receptor_tipo_doc <> '1' or regexp_like(receptor_num_doc, '^[0-9]{8}$')) and
        (receptor_tipo_doc <> '6' or regexp_like(receptor_num_doc, '^(10|15|17|20)[0-9]{9}$')) and
        (tipo <> 'FACTURA' or receptor_tipo_doc = '6')),
    constraint ck_comprobantes_montos check (
        porcentaje_igv >= 0 and op_gravadas >= 0 and igv >= 0 and total > 0
        and total = op_gravadas + igv),
    constraint ck_comprobantes_intentos check (intentos >= 0)
);

-- ---------------------------------------------------------------------
-- 3. Detalle enviado a SUNAT (copia congelada de las líneas)
-- ---------------------------------------------------------------------
create table comprobante_detalles (
    id               number(19,0) generated by default as identity,
    comprobante_id   number(19,0)       not null,
    item             number(5,0)        not null,
    codigo           varchar2(30 char),
    descripcion      varchar2(250 char) not null,
    unidad           varchar2(3 char)   default 'NIU' not null,
    cantidad         number(12,3)       not null,
    valor_unitario   number(14,4)       not null,
    precio_unitario  number(14,4)       not null,
    valor_venta      number(14,2)       not null,
    igv              number(14,2)       not null,
    total            number(14,2)       not null,
    version          number(19,0)       default 0 not null,
    creado_en        timestamp(9) with time zone not null,
    actualizado_en   timestamp(9) with time zone not null,
    creado_por       varchar2(160 char) not null,
    actualizado_por  varchar2(160 char) not null,
    constraint pk_comprobante_detalles primary key (id),
    constraint uq_comprobante_detalles_item unique (comprobante_id, item),
    constraint fk_comprobante_detalles foreign key (comprobante_id) references comprobantes (id),
    constraint ck_comprobante_detalles check (
        item > 0 and cantidad > 0 and valor_unitario >= 0 and precio_unitario >= 0
        and valor_venta >= 0 and igv >= 0 and total = valor_venta + igv),
    constraint ck_comprobante_detalles_unidad check (unidad in ('NIU', 'ZZ'))
);

-- ---------------------------------------------------------------------
-- 4. Índices
-- ---------------------------------------------------------------------
-- Una sola boleta/factura vigente por venta y por contrato (las anuladas no cuentan).
create unique index uq_comprobantes_venta_vigente on comprobantes (
    case when tipo in ('BOLETA', 'FACTURA') and estado <> 'ANULADO' then venta_id end);
create unique index uq_comprobantes_contrato_vigente on comprobantes (
    case when tipo in ('BOLETA', 'FACTURA') and estado <> 'ANULADO' then contrato_id end);
create index ix_series_local              on series_comprobante (local_id);
create index ix_comprobantes_local_fecha  on comprobantes (local_id, fecha_emision);
create index ix_comprobantes_serie        on comprobantes (serie_id);
create index ix_comprobantes_venta        on comprobantes (venta_id);
create index ix_comprobantes_contrato     on comprobantes (contrato_id);
create index ix_comprobantes_referencia   on comprobantes (referencia_id);
create index ix_comprobantes_estado       on comprobantes (estado);
create index ix_comprobante_detalles      on comprobante_detalles (comprobante_id);

-- ---------------------------------------------------------------------
-- 5. Series iniciales del 'Local principal'
--    Si hay más locales, cada uno necesita sus propias series (B002, F002...).
-- ---------------------------------------------------------------------
insert into series_comprobante (local_id, tipo, serie, creado_en, actualizado_en, creado_por, actualizado_por)
select l.id, s.tipo, s.serie, systimestamp, systimestamp, 'script', 'script'
  from locales l
 cross join (select 'BOLETA' tipo, 'B001' serie from dual union all
             select 'FACTURA', 'F001' from dual union all
             select 'NOTA_CREDITO_BOLETA', 'BC01' from dual union all
             select 'NOTA_CREDITO_FACTURA', 'FC01' from dual) s
 where l.nombre = 'Local principal';
commit;

